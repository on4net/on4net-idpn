import { randomBytes } from 'node:crypto';

/**
 * Single-use WebAuthn ceremonies (`docs/security.md` 3.3).
 *
 * The browser receives the public-key options (including the random challenge); the server
 * keeps the challenge, the RP ID, the allowed origins and the owning user in Redis under an
 * opaque, unguessable id. Verification consumes the record atomically, so a captured
 * registration/authentication response cannot be replayed. A login ceremony additionally
 * embeds the pending MFA challenge token, so a WebAuthn challenge issued for one login can
 * never complete a different one.
 */

export const WEBAUTHN_CHALLENGE_TTL_SECONDS = 300;

const KEY = 'idpn:webauthn:ceremony:';
const ID_PATTERN = /^[A-Za-z0-9_-]{20,128}$/;

export type WebauthnCeremony = 'registration' | 'authentication';

/** Why a ceremony was started; the verifier enforces that only the matching use is allowed. */
export type WebauthnPurpose = 'enroll' | 'step_up' | 'login';

export interface WebauthnChallengeRecord {
  /** Base64url challenge generated by the WebAuthn library and sent to the browser. */
  challenge: string;
  userId: string;
  tenantId: string;
  ceremony: WebauthnCeremony;
  purpose: WebauthnPurpose;
  rpId: string;
  origins: string[];
  /** Set only for `purpose = login`: the MFA challenge this ceremony belongs to. */
  mfaChallengeToken?: string;
  createdAt: string;
  expiresAt: string;
}

export interface CreateWebauthnChallengeInput extends Omit<
  WebauthnChallengeRecord,
  'createdAt' | 'expiresAt'
> {
  now?: Date;
}

export interface CreatedWebauthnChallenge {
  /** Opaque handle returned to the browser beside the public-key options. */
  id: string;
  record: WebauthnChallengeRecord;
}

export interface WebauthnChallengeStore {
  create(input: CreateWebauthnChallengeInput): Promise<CreatedWebauthnChallenge>;
  /** Atomic read-and-delete; `null` for unknown, expired or already consumed ceremonies. */
  consume(id: string): Promise<WebauthnChallengeRecord | null>;
}

export function isWebauthnChallengeId(value: string): boolean {
  return ID_PATTERN.test(value);
}

function parse(raw: string): WebauthnChallengeRecord | null {
  try {
    const parsed = JSON.parse(raw) as Partial<WebauthnChallengeRecord>;
    if (
      typeof parsed.challenge !== 'string' ||
      typeof parsed.userId !== 'string' ||
      typeof parsed.tenantId !== 'string' ||
      (parsed.ceremony !== 'registration' && parsed.ceremony !== 'authentication') ||
      (parsed.purpose !== 'enroll' && parsed.purpose !== 'step_up' && parsed.purpose !== 'login') ||
      typeof parsed.rpId !== 'string' ||
      !Array.isArray(parsed.origins) ||
      parsed.origins.some((origin) => typeof origin !== 'string') ||
      typeof parsed.createdAt !== 'string' ||
      typeof parsed.expiresAt !== 'string'
    ) {
      return null;
    }
    return {
      challenge: parsed.challenge,
      userId: parsed.userId,
      tenantId: parsed.tenantId,
      ceremony: parsed.ceremony,
      purpose: parsed.purpose,
      rpId: parsed.rpId,
      origins: [...parsed.origins],
      ...(typeof parsed.mfaChallengeToken === 'string'
        ? { mfaChallengeToken: parsed.mfaChallengeToken }
        : {}),
      createdAt: parsed.createdAt,
      expiresAt: parsed.expiresAt,
    };
  } catch {
    return null;
  }
}

function build(input: CreateWebauthnChallengeInput): WebauthnChallengeRecord {
  const now = input.now ?? new Date();
  return {
    challenge: input.challenge,
    userId: input.userId,
    tenantId: input.tenantId,
    ceremony: input.ceremony,
    purpose: input.purpose,
    rpId: input.rpId,
    origins: [...input.origins],
    ...(input.mfaChallengeToken === undefined
      ? {}
      : { mfaChallengeToken: input.mfaChallengeToken }),
    createdAt: now.toISOString(),
    expiresAt: new Date(now.getTime() + WEBAUTHN_CHALLENGE_TTL_SECONDS * 1000).toISOString(),
  };
}

/** Structural subset of the Redis client (same style as `RedisMfaChallengeStore`). */
export interface WebauthnChallengeRedis {
  getdel(key: string): Promise<string | null>;
  set(key: string, value: string, mode: 'EX', seconds: number): Promise<unknown>;
}

export class RedisWebauthnChallengeStore implements WebauthnChallengeStore {
  constructor(private readonly redis: WebauthnChallengeRedis) {}

  async create(input: CreateWebauthnChallengeInput): Promise<CreatedWebauthnChallenge> {
    const id = randomBytes(32).toString('base64url');
    const record = build(input);
    await this.redis.set(
      `${KEY}${id}`,
      JSON.stringify(record),
      'EX',
      WEBAUTHN_CHALLENGE_TTL_SECONDS,
    );
    return { id, record };
  }

  async consume(id: string): Promise<WebauthnChallengeRecord | null> {
    if (!isWebauthnChallengeId(id)) {
      return null;
    }
    const raw = await this.redis.getdel(`${KEY}${id}`);
    return raw === null ? null : parse(raw);
  }
}

interface Entry {
  value: WebauthnChallengeRecord;
  expiresAt: number;
}

/** In-memory store with identical TTL/single-use semantics for unit tests and dev. */
export class MemoryWebauthnChallengeStore implements WebauthnChallengeStore {
  private readonly entries = new Map<string, Entry>();
  private readonly now: () => number;

  constructor(options: { now?: () => number } = {}) {
    this.now = options.now ?? (() => Date.now());
  }

  async create(input: CreateWebauthnChallengeInput): Promise<CreatedWebauthnChallenge> {
    const id = randomBytes(32).toString('base64url');
    const record = build({ ...input, now: input.now ?? new Date(this.now()) });
    this.entries.set(id, {
      value: record,
      expiresAt: this.now() + WEBAUTHN_CHALLENGE_TTL_SECONDS * 1000,
    });
    return { id, record };
  }

  async consume(id: string): Promise<WebauthnChallengeRecord | null> {
    if (!isWebauthnChallengeId(id)) {
      return null;
    }
    const entry = this.entries.get(id);
    this.entries.delete(id);
    if (entry === undefined || entry.expiresAt <= this.now()) {
      return null;
    }
    return entry.value;
  }
}
